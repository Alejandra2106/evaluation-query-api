-- Réplica mínima, solo para pruebas con H2, de las tablas de scoring-api (migraciones V1-V9) que lee
-- evaluation-query-api. No es una migración ni se usa fuera de las pruebas. La compatibilidad de las
-- consultas con el esquema real la comprueba EsquemaScoringContratoIT sobre PostgreSQL.

CREATE TABLE solicitante (
    id_solicitante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(100) NOT NULL,
    numero_documento VARCHAR(15) NOT NULL,
    ingresos_mensuales NUMERIC(15, 2) NOT NULL,
    deudas_mensuales NUMERIC(15, 2) NOT NULL,
    numero_moras INTEGER NOT NULL,
    historial_crediticio VARCHAR(10) NOT NULL,
    antiguedad_laboral NUMERIC(5, 2) NOT NULL,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE riesgo (
    id_riesgo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variable VARCHAR(30) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    estado VARCHAR(10) DEFAULT 'ACTIVA' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_modificacion TIMESTAMP
);

CREATE TABLE regla_scoring (
    id_regla BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_riesgo BIGINT NOT NULL REFERENCES riesgo (id_riesgo),
    operador VARCHAR(2) NOT NULL,
    valor_condicion VARCHAR(255) NOT NULL,
    puntaje INTEGER NOT NULL,
    estado VARCHAR(10) DEFAULT 'ACTIVA' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE politica_clasificacion (
    id_politica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_publicacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    publicado_por UUID
);

CREATE TABLE evaluacion (
    id_evaluacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitante BIGINT NOT NULL REFERENCES solicitante (id_solicitante),
    fecha_evaluacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    score_total INTEGER,
    categoria VARCHAR(10),
    id_politica BIGINT REFERENCES politica_clasificacion (id_politica)
);

CREATE TABLE detalle_evaluacion (
    id_detalle_evaluacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion BIGINT NOT NULL REFERENCES evaluacion (id_evaluacion),
    id_regla BIGINT NOT NULL REFERENCES regla_scoring (id_regla),
    operador_aplicado VARCHAR(2) NOT NULL,
    valor_condicion_aplicado VARCHAR(255) NOT NULL,
    puntaje_regla_aplicado INTEGER NOT NULL,
    condicion_cumplida BOOLEAN NOT NULL,
    puntaje_obtenido INTEGER NOT NULL
);
