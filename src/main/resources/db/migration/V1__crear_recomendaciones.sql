-- HU14: recomendaciones generadas, en el esquema propio de evaluation-query-api (por defecto "consulta").
-- Flyway de esta API solo gestiona este esquema; nunca ejecuta migraciones sobre public (datos de
-- scoring-api, que esta API solo lee). Las funciones fijan search_path al esquema de la migración.

-- Cabecera de la generación: existe aunque no haya ninguna recomendación aplicable, para distinguir "generada
-- con cero recomendaciones" de "todavía no generada". Su clave primaria hace idempotentes los reintentos.
CREATE TABLE generacion_recomendaciones (
    id_evaluacion      BIGINT      PRIMARY KEY,
    version_catalogo   VARCHAR(30) NOT NULL,
    categoria_aplicada VARCHAR(10) NOT NULL,
    fecha_generacion   TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_generacion_recomendaciones_categoria
        CHECK (categoria_aplicada IN ('BAJO', 'MEDIO', 'ALTO'))
);

-- Copia histórica de cada recomendación (CA05): código, texto y criterio de activación tal como estaban en la
-- versión del catálogo usada (la versión está en la cabecera).
CREATE TABLE recomendacion_evaluacion (
    id_recomendacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion    BIGINT       NOT NULL,
    orden            INTEGER      NOT NULL,
    codigo           VARCHAR(50)  NOT NULL,
    texto            VARCHAR(500) NOT NULL,
    tipo_activacion  VARCHAR(20)  NOT NULL,
    categoria        VARCHAR(10)  NULL,
    variable         VARCHAR(30)  NULL,
    CONSTRAINT fk_recomendacion_evaluacion_generacion
        FOREIGN KEY (id_evaluacion) REFERENCES generacion_recomendaciones (id_evaluacion),
    CONSTRAINT uq_recomendacion_evaluacion_codigo UNIQUE (id_evaluacion, codigo),
    CONSTRAINT uq_recomendacion_evaluacion_orden UNIQUE (id_evaluacion, orden),
    CONSTRAINT ck_recomendacion_evaluacion_orden CHECK (orden >= 1),
    CONSTRAINT ck_recomendacion_evaluacion_activacion CHECK (
        (tipo_activacion = 'CATEGORIA' AND categoria IN ('BAJO', 'MEDIO', 'ALTO') AND variable IS NULL)
        OR (tipo_activacion = 'FACTOR_DESFAVORABLE' AND variable IS NOT NULL AND categoria IS NULL))
);

-- Inmutabilidad (CA05, CA06): una generación guardada no se modifica, no se borra ni se sobrescribe.
CREATE FUNCTION fn_tg_recomendaciones_inmutables() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ${flyway:defaultSchema}, pg_temp
AS $$
BEGIN
    RAISE EXCEPTION 'Las recomendaciones generadas son inmutables'
        USING ERRCODE = 'object_not_in_prerequisite_state';
END;
$$;

CREATE TRIGGER tg_generacion_recomendaciones_inmutable
    BEFORE UPDATE OR DELETE ON generacion_recomendaciones
    FOR EACH ROW EXECUTE FUNCTION fn_tg_recomendaciones_inmutables();

CREATE TRIGGER tg_generacion_recomendaciones_sin_truncate
    BEFORE TRUNCATE ON generacion_recomendaciones
    FOR EACH STATEMENT EXECUTE FUNCTION fn_tg_recomendaciones_inmutables();

CREATE TRIGGER tg_recomendacion_evaluacion_inmutable
    BEFORE UPDATE OR DELETE ON recomendacion_evaluacion
    FOR EACH ROW EXECUTE FUNCTION fn_tg_recomendaciones_inmutables();

CREATE TRIGGER tg_recomendacion_evaluacion_sin_truncate
    BEFORE TRUNCATE ON recomendacion_evaluacion
    FOR EACH STATEMENT EXECUTE FUNCTION fn_tg_recomendaciones_inmutables();
